export function buildWalletsFromLedger(ledger: LedgerTransaction[]): Wallet[] {
  return WALLET_META.map((meta) => {
    const { availableBalancePaise, heldBalancePaise } =
      calculateWalletBalancesFromLedger(ledger, meta.id);
    const userTxns = ledger.filter((t) => t.walletId === meta.id);
    const latest = userTxns.reduce(
      (max, t) => (t.createdAt > max ? t.createdAt : max),
      meta.createdAt,
    );
    return {
      ...meta,
      availableBalancePaise,
      heldBalancePaise,
      updatedAt: latest,
    };
  });
}

