/** Overall account approval ignores optional pending corporate. */
export function isIdentityApprovedForOperations(
  records: Pick<VerificationRecord, "type" | "status" | "requirement">[],
): boolean {
  const required = records.filter((r) => r.requirement === "required");
  if (required.length === 0) return false;
  return required.every((r) => r.status === "APPROVED");
}
