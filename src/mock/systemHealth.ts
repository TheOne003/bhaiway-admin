export function buildSystemHealthSummary(
  services: ServiceHealthDetail[],
  checkedAt = FIXED_CHECKED_AT,
): SystemHealthSummary {
  const counts = countByStatus(services);
  return {
    overall: deriveOverallStatus(services),
    counts,
    operationalCount: counts.operational,
    degradedCount: counts.degraded,
    downCount: counts.down,
    services: structuredClone(services),
    checkedAt,
  };
}

